/** Ключ флага словами: «cannot_speak_non_thri_kreen» → «Cannot speak non thri kreen» */
export function humanizeKey(key: string): string {
  const s = key.replace(/[_.]+/g, ' ').trim()
  return s ? s[0].toUpperCase() + s.slice(1) : key
}

/**
 * Подпись флага: словарь → подпись узла каталога → название способности-источника
 * (из расшифровки листа) → ключ.
 */
export function flagLabel(key: string, nodeLabel: string | undefined, sourceName: string | undefined): string {
  if (FLAG_RU[key]) return FLAG_RU[key]
  if (nodeLabel && /[а-яё]/i.test(nodeLabel)) return nodeLabel
  if (sourceName) return sourceName
  return nodeLabel ?? humanizeKey(key)
}
