import { describe, expect, it } from 'vitest'
import { richBlocks } from './terms'

describe('richBlocks', () => {
  it('строки «a | b» подряд — таблица с заголовком', () => {
    const b = richBlocks([
      'Быстрое изготовление',
      'Ремесленные инструменты | Изготавливаемое снаряжение',
      'Инструменты гончара | Кувшин, Лампа',
      'Инструменты каменщика | Блок и лебедка',
      'После таблицы.',
    ])
    expect(b.map((x) => x.kind)).toEqual(['p', 'table', 'p'])
    expect(b[1]).toEqual({
      kind: 'table',
      rows: [
        ['Ремесленные инструменты', 'Изготавливаемое снаряжение'],
        ['Инструменты гончара', 'Кувшин, Лампа'],
        ['Инструменты каменщика', 'Блок и лебедка'],
      ],
    })
  })

  it('одиночная строка с « | » остаётся абзацем', () => {
    expect(richBlocks(['Один | два'])).toEqual([{ kind: 'p', text: 'Один | два' }])
  })
})
