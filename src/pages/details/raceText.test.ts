import { describe, expect, it } from 'vitest'
import { isRaceText2024, parseRaceText } from './raceText'

const AASIMAR = `Тип существа: Гуманоид. Размер: Средний (рост около 4-7 футов) или Маленький; выберите вместе с видом. Скорость: 30 футов.

Небесное сопротивление. У вас есть Сопротивление Некротическому урону.
Тёмное зрение. У вас есть Тёмное зрение дальностью 60 футов.
Небесное откровение. По достижении 3-го уровня вы можете преобразиться.
Пока преобразование действует, вы наносите дополнительный урон.
Вы выбираете преобразование из следующих вариантов:
Небесные крылья. Два призрачных крыла вырастают из вашей спины.
Сияющая душа. Обжигающий свет исходит из ваших глаз.
Саван смерти. Ваши глаза превращаются в озера тьмы.

Аасимары — смертные с искрой Верхних Планов.`

describe('parseRaceText', () => {
  it('параметры, особенности, варианты внутри и рассказ', () => {
    expect(isRaceText2024(AASIMAR)).toBe(true)
    const r = parseRaceText(AASIMAR)
    expect(r.params.map(([k]) => k)).toEqual(['Тип существа', 'Размер', 'Скорость'])
    expect(r.params[2][1]).toBe('30 футов')
    expect(r.traits.map((t) => t.name)).toEqual(['Небесное сопротивление', 'Тёмное зрение', 'Небесное откровение'])
    const rev = r.traits[2]
    expect(rev.body).toHaveLength(3)
    expect(rev.options.map((o) => o.name)).toEqual(['Небесные крылья', 'Сияющая душа', 'Саван смерти'])
    expect(r.lore).toBe('Аасимары — смертные с искрой Верхних Планов.')
  })

  it('варианты наследия', () => {
    const r = parseRaceText('Тип существа: Гуманоид. Скорость: 30 футов.\n\nТранс. Вам не нужно спать.\n\nВарианты: Высший эльф, Дроу.\n\nРассказ.')
    expect(r.variants).toBe('Высший эльф, Дроу')
    expect(r.lore).toBe('Рассказ.')
  })
})
