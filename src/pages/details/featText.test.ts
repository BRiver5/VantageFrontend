import { describe, expect, it } from 'vitest'
import { formatFeatText } from './featText'

describe('formatFeatText', () => {
  it('строки «Название. Текст» — пункты с жирным названием', () => {
    const out = formatFeatText('Вы получаете следующие преимущества:\nВладение Инициативой. Когда вы совершаете бросок…\nОбмен Инициативой. Сразу после…')
    expect(out.split('\n')).toEqual([
      'Вы получаете следующие преимущества:',
      '**Владение Инициативой.** Когда вы совершаете бросок…',
      '**Обмен Инициативой.** Сразу после…',
    ])
  })

  it('обычные предложения не трогает', () => {
    expect(formatFeatText('Когда вы атакуете. Потом ещё.')).toBe('Когда вы атакуете. Потом ещё.')
    expect(formatFeatText('Вы получаете бонус. Он растёт.')).toBe('Вы получаете бонус. Он растёт.')
  })
})
