/**
 * Описание черты 2024 приходит плоским текстом: вступление («Вы получаете следующие
 * преимущества:») и строки «Название. Текст». Строки с названием превращаются в пункты
 * с жирным названием (**…** понимает RichText), остальное остаётся абзацами.
 */

/** Так начинаются обычные предложения, а не названия пунктов */
const SENTENCE_START = /^(Вы|Вам|Вас|Ваш|Ваша|Ваше|Ваши|Когда|Если|Пока|Это|Эта|Этот|При|После|Каждый|Каждая|Один|Одна|Как|Тот|Та|Те|В|На|С|До|Если|Чтобы|Существо|Цель|Затем|Также|Кроме)(?=\s|$)/

const POINT = /^([А-ЯЁA-Z][^.:!?\n]{1,60})\.\s+(\S[\s\S]*)$/

/** «Владение Инициативой. Когда…» → «**Владение Инициативой.** Когда…» */
export function formatFeatText(text: string | null | undefined): string {
  if (!text) return ''
  return text
    .split('\n')
    .map((line) => {
      const t = line.trim()
      const m = POINT.exec(t)
      if (!m) return line
      const name = m[1].trim()
      if (SENTENCE_START.test(name) || name.split(/\s+/).length > 5) return line
      return `**${name}.** ${m[2]}`
    })
    .join('\n')
}
