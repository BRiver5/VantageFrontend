export function raceHeight(creatureType: string | null | undefined) {
  const note = creatureType?.match(/\(([^)]*)\)/)?.[1].toLocaleLowerCase('ru')
  if (!note) return null
  const hit = RACE_HEIGHTS.find(([stem]) => note.includes(stem))
  return hit && hit[2] ? { race: hit[1], m: hit[2] } : null
}

export const fmtM = (m: number) => `${String(Math.round(m * 100) / 100).replace('.', ',')} м`

/** Средний рост игровой расы по названию; null — расы нет в таблице */
export function raceAverageHeight(raceName: string | null | undefined): number | null {
  const name = raceName?.toLocaleLowerCase('ru')
  if (!name) return null
  const hit = RACE_HEIGHTS.find(([stem]) => name.includes(stem))
  return hit && hit[2] ? hit[2] : null
}

/** Типичный рост и рамки категории размера (DMG) */
export function sizeHeightRange(size: string | null | undefined) {
  const info = SIZES.find((s) => s.key === size?.trim().toLowerCase())
  return info ? { m: info.m, min: info.min, max: info.max } : null
}
